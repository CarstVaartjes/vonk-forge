"""What the pinned LiteLLM accepts in an external entry: one document per pin.

``deploy/compose/litellm/surface.json`` is generated by ``tools/litellm_surface.py``
inside the pinned image and committed.  CI regenerates it and fails on any byte
difference, and the unit test ties its digest to ``images.lock.json``, so a
LiteLLM bump cannot ship without a fresh surface.  LiteLLM never reports an
unknown key (its parameter models allow extras), so this document, not LiteLLM,
decides which fields exist.
"""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

from pydantic import JsonValue

from vonk_agent_protocol.identifiers import OciDigest
from vonk_control.stored.json_values import ExternalPassthrough
from vonk_control.strict_json import StrictModel

JsonSchemaDocument = Annotated[
    JsonValue,
    ExternalPassthrough(
        "A JSON Schema generated from a LiteLLM field annotation; LiteLLM defines it."
    ),
]


class LiteLlmSurface(StrictModel):
    """The providers, ``litellm_params`` fields and ``model_info`` fields of one pin."""

    litellm_version: str
    image_digest: OciDigest
    providers: list[str]
    litellm_params: dict[str, JsonSchemaDocument]
    model_info: dict[str, JsonSchemaDocument]


def load_surface(path: Path) -> LiteLlmSurface:
    """Read the generated document; a malformed file raises a validation error."""

    return LiteLlmSurface.model_validate_json(path.read_bytes())
